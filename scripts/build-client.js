import { readFileSync, writeFileSync } from 'node:fs'
import { buildSync } from 'esbuild'
import { fileURLToPath } from 'node:url'
const root = new URL('../', import.meta.url)
const model = readFileSync(new URL('model.js', root), 'utf8').replace(/^export /gm, '')
const source = readFileSync(new URL('client-source.js', root), 'utf8')
const css = readFileSync(new URL('desk.css', root), 'utf8')
const contents = source.replace('/* MODEL */', model).replace('/* CSS */', JSON.stringify(css))
const result=buildSync({stdin:{contents,resolveDir:fileURLToPath(root),sourcefile:'client-source.js'},bundle:true,loader:{'.png':'dataurl','.jpg':'dataurl','.svg':'dataurl'},format:'iife',write:false,target:'chrome110',legalComments:'inline'})
writeFileSync(new URL('client.js', root), '// Generated by npm run build. Edit client-source.js, model.js or desk.css.\n'+result.outputFiles[0].text)
